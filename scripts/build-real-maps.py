"""Clip public-domain Natural Earth 1:10m land into offline mission maps.

Usage: PYTHONPATH=<shapely install> python scripts/build-real-maps.py SOURCE.geojson
Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_10m_land.geojson
Shapely is only a development dependency; the deployed game has no dependencies.
"""
import hashlib
import json
import math
import sys
from pathlib import Path
from shapely.geometry import shape, box
from shapely.ops import unary_union

source = Path(sys.argv[1])
world = unary_union([shape(f['geometry']) for f in json.loads(source.read_text())['features']])
specs = {
    'bubiyan': {'name':'布比延岛与波斯湾北部','west':47.65,'east':49.35,'north':30.25,'south':28.95,
        'labels':[['布比延岛',48.23,29.80],['科威特湾',47.95,29.43],['法奥半岛',48.40,30.01],['波斯湾北部',48.94,29.37],['伊朗海岸',48.93,30.02]]},
    'hormuz': {'name':'霍尔木兹海峡与拉腊克岛','west':55.2,'east':57.4,'north':27.3,'south':25.6,
        'labels':[['格什姆岛',55.80,26.82],['拉腊克岛',56.36,26.85],['阿巴斯港',56.28,27.17],['穆桑代姆半岛',56.30,26.16],['霍尔木兹海峡',56.50,26.55]]},
    'falklands': {'name':'圣卡洛斯水道与福克兰海峡','west':-59.75,'east':-58.5,'north':-51.15,'south':-51.9,
        'labels':[['西福克兰岛',-59.60,-51.55],['东福克兰岛',-58.65,-51.47],['福克兰海峡',-59.26,-51.65],['圣卡洛斯水道',-59.05,-51.51],['北部入口',-59.17,-51.29]]},
}
for key, spec in specs.items():
    spec['referenceLatitude'] = (spec['north'] + spec['south']) / 2
    factor = 60 * math.cos(math.radians(spec['referenceLatitude']))
    spec['width'] = round((spec['east']-spec['west'])*factor, 6)
    spec['height'] = round((spec['north']-spec['south'])*60, 6)
    clipped = world.intersection(box(spec['west'],spec['south'],spec['east'],spec['north'])).simplify(.0003,preserve_topology=True)
    polygons = list(clipped.geoms) if hasattr(clipped,'geoms') else [clipped]
    spec['land'] = [[[round((x-spec['west'])*factor,5),round((spec['north']-y)*60,5)] for x,y in p.exterior.coords] for p in polygons if p.geom_type=='Polygon' and p.area>.0000001]
    spec['source'] = 'Natural Earth 1:10m land · public domain'
    spec['sourceURL'] = 'https://www.naturalearthdata.com/about/terms-of-use/'
    spec['sourceSHA256'] = hashlib.sha256(source.read_bytes()).hexdigest()
    print(key, spec['width'], spec['height'], len(spec['land']), sum(len(r) for r in spec['land']))
destination=Path(__file__).resolve().parents[1]/'dist'/'real-coastlines.js'
destination.write_text('// Generated by scripts/build-real-maps.py. Natural Earth public-domain geography.\nexport const REAL_MAPS='+json.dumps(specs,ensure_ascii=False,separators=(',',':'))+';\n')
